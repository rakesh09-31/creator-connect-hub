/**
 * Finds the canonical role evidence definition for a target role or alias.
 * Strictly uses getCanonicalRole first, avoiding dangerous substring overlaps.
 */
export function findRoleDef(targetRole: string): RoleEvidenceDef | undefined {
  if (!targetRole) return undefined;
  const trimmed = targetRole.trim();
  const canon = getCanonicalRole(trimmed);

  if (canon) {
    const key = canon.toLowerCase();
    if (ROLE_TAXONOMY[key]) return ROLE_TAXONOMY[key];
    const found = Object.values(ROLE_TAXONOMY).find(
      (d) => d.canonicalRole.toLowerCase() === canon.toLowerCase()
    );
    if (found) return found;
  }

  const norm = normalizeRoleKey(trimmed);
  if (ROLE_TAXONOMY[norm]) return ROLE_TAXONOMY[norm];

  for (const def of Object.values(ROLE_TAXONOMY)) {
    if (def.roleAliases.some((a) => a.toLowerCase() === trimmed.toLowerCase() || normalizeRoleKey(a) === norm)) {
      return def;
    }
  }

  return undefined;
}
